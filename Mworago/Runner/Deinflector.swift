import Foundation

/// 활용형을 사전형으로 되돌린 결과.
public struct Deinflection: Sendable, Equatable {
    public let form: String    // 되돌린 형태
    public let rule: String?   // 어떤 활용이었나. nil이면 손대지 않은 원문
}

/// 활용형을 사전에서 찾을 수 있는 형태로 되돌린다.
///
/// JMdict는 사전형만 싣는다. `やめる`는 있어도 `やめろ`는 없다.
/// 그런데 애니 대사는 대부분 활용형이다 — 명령형("야메로!"), 과거형("요캇타"), て형("타스케테").
/// 사전을 날것으로 쓰면 앱이 정확히 노리는 문장에서 가장 많이 터진다.
///
/// 여기서도 원칙은 같다. **후보를 펼치고 고르는 일은 사전에 맡긴다.**
/// `った`가 う·つ·る 중 무엇에서 왔는지는 형태만 봐서 알 수 없으므로 셋 다 낸다.
public enum Deinflector {

    /// 5단 동사 정중형은 어간이 い단으로 바뀐다. 되돌리려면 う단으로 옮긴다.
    ///
    /// `ます` 를 떼고 `る` 만 붙이면 1단(たべます → たべる)은 맞지만 5단은
    /// `よみます → よみる` 가 된다. 어느 쪽인지는 형태만 봐서 알 수 없으므로 둘 다 낸다.
    private static let iToU: [Character: Character] = [
        "い": "う", "き": "く", "ぎ": "ぐ", "し": "す", "じ": "ず",
        "ち": "つ", "ぢ": "づ", "に": "ぬ", "ひ": "ふ", "び": "ぶ",
        "ぴ": "ぷ", "み": "む", "り": "る",
    ]

    /// 정중형 어미. 어미마다 뒤가 다를 뿐 어간을 되돌리는 방법은 같다.
    private static let politeSuffixes = ["ます", "ました", "ません", "ましょう"]

    /// 5단 동사 명령형은 어미가 え단으로 바뀐다. 되돌리려면 う단으로 옮긴다.
    private static let eToU: [Character: Character] = [
        "え": "う", "け": "く", "げ": "ぐ", "せ": "す", "ぜ": "ず",
        "て": "つ", "で": "づ", "ね": "ぬ", "へ": "ふ", "べ": "ぶ",
        "ぺ": "ぷ", "め": "む", "れ": "る",
    ]

    /// (어미, 붙일 것들, 활용 이름). 어미를 떼고 각각을 붙인 형태가 후보가 된다.
    private static let rules: [(suffix: String, replacements: [String], name: String)] = [
        // 과거형 — 음편이 있는 5단이 먼저, 짧은 규칙이 뒤
        ("かった", ["い"],            "과거형"),   // い형용사: よかった → よい
        ("った",  ["う", "つ", "る"], "과거형"),
        ("いた",  ["く"],            "과거형"),
        ("いだ",  ["ぐ"],            "과거형"),
        ("んだ",  ["ぶ", "む", "ぬ"], "과거형"),
        ("した",  ["す", "する"],    "과거형"),   // サ変: べんきょうした → べんきょうする
        ("た",    ["る"],            "과거형"),   // 1단: つかれた → つかれる

        // て형
        ("って",  ["う", "つ", "る"], "て형"),
        ("いて",  ["く"],            "て형"),
        ("いで",  ["ぐ"],            "て형"),
        ("んで",  ["ぶ", "む", "ぬ"], "て형"),
        ("して",  ["す", "する"],    "て형"),
        ("て",    ["る"],            "て형"),

        // 진행형 축약 — ている 는 말할 때 거의 항상 てる 로 줄어든다.
        // 애니 대사에서는 줄지 않은 쪽이 오히려 드물다. て형 규칙에 る 를 붙인 꼴이다.
        ("ってる", ["う", "つ", "る"], "진행형"),
        ("いてる", ["く"],            "진행형"),
        ("いでる", ["ぐ"],            "진행형"),
        ("んでる", ["ぶ", "む", "ぬ"], "진행형"),
        ("してる", ["す", "する"],    "진행형"),   // 어간이 없으면 する 자체다
        ("てる",   ["る"],            "진행형"),
        ("でる",   ["る"],            "진행형"),

        // 줄지 않은 원형. 축약형(てる)만 있어서 문장에서 いる 가 통째로 떨어져 나갔다 —
        // 틀린 분절의 꼬리 1위가 `이루` 31건이었다. 대사에서는 줄여 말하지만
        // 자막과 코퍼스에는 원형이 그대로 적힌다.
        ("っている", ["う", "つ", "る"], "진행형"),
        ("いている", ["く"],            "진행형"),
        ("いでいる", ["ぐ"],            "진행형"),
        ("んでいる", ["ぶ", "む", "ぬ"], "진행형"),
        ("している", ["す", "する"],    "진행형"),
        ("ている",   ["る"],            "진행형"),
        ("でいる",   ["る"],            "진행형"),

        ("っていた", ["う", "つ", "る"], "진행형 과거"),
        ("いていた", ["く"],            "진행형 과거"),
        ("いでいた", ["ぐ"],            "진행형 과거"),
        ("んでいた", ["ぶ", "む", "ぬ"], "진행형 과거"),
        ("していた", ["す", "する"],    "진행형 과거"),
        ("ていた",   ["る"],            "진행형 과거"),
        ("でいた",   ["る"],            "진행형 과거"),

        ("ってた", ["う", "つ", "る"], "진행형 과거"),
        ("いてた", ["く"],            "진행형 과거"),
        ("いでた", ["ぐ"],            "진행형 과거"),
        ("んでた", ["ぶ", "む", "ぬ"], "진행형 과거"),
        ("してた", ["す", "する"],    "진행형 과거"),
        ("てた",   ["る"],            "진행형 과거"),
        ("でた",   ["る"],            "진행형 과거"),

        // 그 밖
        ("ろ",    ["る"],            "명령형"),   // 1단: やめろ → やめる
        ("ない",  ["る"],            "부정형"),
        ("で",    [""],              "조사 で"),  // まじで → まじ

        // 불규칙 — 来る·する 둘뿐이고, 둘 다 최빈출이다.
        //
        // 어간이 통째로 갈려서(来: き·こ·く / す: し·す·せ) 어미 규칙으로는 되돌릴 수 없다.
        // `きた` 를 "た → る" 로 풀면 きる(着る)만 나오고 くる 는 후보에 오르지도 못한다.
        // 그래서 형태마다 적는다. 어간이 남으면 복합 동사다(やってきた → やってくる).
        ("きた",   ["くる"],          "과거형"),
        ("きて",   ["くる"],          "て형"),
        ("きてる", ["くる"],          "진행형"),
        ("きている", ["くる"],        "진행형"),
        ("きていた", ["くる"],        "진행형 과거"),
        ("きました", ["くる"],        "정중형"),
        ("しました", ["する"],        "정중형"),
        ("きてた", ["くる"],          "진행형 과거"),
        ("きます", ["くる"],          "정중형"),
        ("こない", ["くる"],          "부정형"),
        ("こい",   ["くる"],          "명령형"),
        ("これる", ["くる"],          "가능형"),
        ("します", ["する"],          "정중형"),
        ("しない", ["する"],          "부정형"),
        ("しろ",   ["する"],          "명령형"),
    ]

    /// 이보다 짧은 말은 건드리지 않는다. "て" 한 글자를 て형으로 보면 오탐만 는다.
    private static let minimumLength = 2

    /// 되돌린 형태들. 첫 번째는 언제나 원문 그대로다(사전에 활용형이 실린 경우가 있다).
    public static func candidates(for kana: String) -> [Deinflection] {
        var results = [Deinflection(form: kana, rule: nil)]
        guard kana.count >= minimumLength else { return results }

        var seen: Set<String> = [kana]
        func add(_ form: String, _ rule: String) {
            guard form.count >= 1, seen.insert(form).inserted else { return }
            results.append(Deinflection(form: form, rule: rule))
        }

        for rule in rules where kana.hasSuffix(rule.suffix) {
            let stem = String(kana.dropLast(rule.suffix.count))
            // 어간이 남지 않는 경우도 있다 — してる 를 떼면 아무것도 안 남지만 する 가 답이다.
            // 그때는 붙일 것 자체가 낱말을 이루어야 한다.
            if stem.isEmpty {
                for replacement in rule.replacements where replacement.count >= 2 {
                    add(replacement, rule.name)
                }
                continue
            }
            for replacement in rule.replacements {
                add(stem + replacement, rule.name)
            }
        }

        // 정중형: 어미를 떼고 1단(+る)과 5단(い단 → う단)을 둘 다 낸다
        for suffix in politeSuffixes where kana.hasSuffix(suffix) {
            let stem = String(kana.dropLast(suffix.count))
            guard !stem.isEmpty else { continue }
            add(stem + "る", "정중형")
            if let last = stem.last, let restored = iToU[last] {
                add(String(stem.dropLast()) + String(restored), "정중형")
            }
        }

        // 5단 명령형: 마지막 글자만 え단 → う단으로 옮긴다
        if let last = kana.last, let restored = eToU[last] {
            add(String(kana.dropLast()) + String(restored), "명령형")
        }

        return results
    }
}
