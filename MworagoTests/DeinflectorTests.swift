import Testing
@testable import MworagoDomain
@testable import MworagoUseCases

@Suite("활용 역변환")
struct DeinflectorTests {

    /// 되돌린 형태들 중 기대한 게 있는지, 그때 활용 이름이 무엇인지 본다.
    func 찾기(_ 입력: String, _ 기대: String) -> Deinflection? {
        Deinflector.candidates(for: 입력).first { $0.form == 기대 }
    }

    @Test("자기 자신도 후보에 남는다")
    func 원형유지() {
        // 사전에 활용형 그대로 실린 항목(疲れた 등)을 놓치지 않기 위해
        let 후보 = Deinflector.candidates(for: "つかれた")
        #expect(후보.first?.form == "つかれた")
        #expect(후보.first?.rule == nil)
    }

    @Test("1단 동사 명령형: ろ → る")
    func 일단명령형() {
        #expect(찾기("やめろ", "やめる")?.rule == "명령형")
        #expect(찾기("きえろ", "きえる")?.rule == "명령형")
    }

    @Test("5단 동사 명령형: え단 → う단")
    func 오단명령형() {
        #expect(찾기("いそげ", "いそぐ")?.rule == "명령형")
        #expect(찾기("だまれ", "だまる")?.rule == "명령형")
        #expect(찾기("がんばれ", "がんばる")?.rule == "명령형")
    }

    @Test("い형용사 과거형: かった → い")
    func 형용사과거() {
        #expect(찾기("よかった", "よい")?.rule == "과거형")
    }

    @Test("1단 동사 て형·과거형")
    func 일단테형() {
        #expect(찾기("たすけて", "たすける")?.rule == "て형")
        #expect(찾기("つかれた", "つかれる")?.rule == "과거형")
    }

    @Test("5단 음편형은 원형 후보를 여럿 낸다")
    func 음편형() {
        // った는 う·つ·る 셋 중 어디서 왔는지 모른다. 고르는 건 사전 몫.
        let 후보 = Deinflector.candidates(for: "わかった").map(\.form)
        #expect(후보.contains("わかる"))
        #expect(후보.contains("わかう"))
        #expect(Deinflector.candidates(for: "よんだ").map(\.form).contains("よむ"))
    }

    @Test("조사 で를 뗀다")
    func 조사분리() {
        #expect(찾기("まじで", "まじ")?.rule == "조사 で")
    }

    @Test("너무 짧으면 건드리지 않는다")
    func 짧은말() {
        // "て" 한 글자를 て형으로 보면 온갖 오탐이 생긴다
        #expect(Deinflector.candidates(for: "て").count == 1)
        #expect(Deinflector.candidates(for: "む").count == 1)
    }

    @Test("진행형 축약 てる 를 되돌린다")
    func 진행형축약() {
        // 애니 대사에서 ている 는 거의 항상 てる 로 줄어든다
        #expect(찾기("たべてる", "たべる")?.rule == "진행형")
        #expect(찾기("よんでる", "よむ")?.rule == "진행형")
        #expect(찾기("かいてる", "かく")?.rule == "진행형")
        #expect(찾기("はなしてる", "はなす")?.rule == "진행형")
    }

    @Test("어간이 없는 축약도 되돌린다")
    func 어간없는축약() {
        // してる 는 する 의 축약이다. 떼고 나면 어간이 남지 않는다
        #expect(찾기("してる", "する")?.rule == "진행형")
        #expect(찾기("してた", "する")?.rule == "진행형 과거")
    }

    @Test("来る 는 형태마다 어간이 갈린다")
    func 카행변격() {
        // 일본어 불규칙 동사는 来る·する 둘뿐인데 둘 다 최빈출이다.
        // 규칙으로는 되돌릴 수 없어 형태마다 적는다 — きた 를 "た → る" 로 풀면
        // きる(着る)만 나오고 くる 는 후보에 오르지도 못한다.
        #expect(찾기("きた", "くる") != nil)
        #expect(찾기("きて", "くる") != nil)
        #expect(찾기("きます", "くる") != nil)
        #expect(찾기("こない", "くる") != nil)
        #expect(찾기("こい", "くる") != nil)
        #expect(찾기("きてる", "くる") != nil)
        // 복합 동사도 어미는 같다.
        #expect(찾기("やってきた", "やってくる") != nil)
        #expect(찾기("でてきて", "でてくる") != nil)
    }

    @Test("する 는 명사에 붙어 동사를 만든다")
    func 사행변격() {
        #expect(찾기("した", "する") != nil)
        #expect(찾기("して", "する") != nil)
        #expect(찾기("します", "する") != nil)
        #expect(찾기("しない", "する") != nil)
        // 명사+する 는 어간이 그대로 남는다.
        #expect(찾기("べんきょうした", "べんきょうする") != nil)
        #expect(찾기("あいして", "あいする") != nil)
    }

    @Test("기존 후보를 밀어내지 않는다")
    func 후보공존() {
        // 불규칙을 더해도 규칙으로 나오던 답은 그대로 있어야 한다.
        // きた 는 着た(きる)일 수도 있다. 두 답이 함께 후보에 있어야 사전이 고를 수 있다.
        #expect(찾기("きた", "きる") != nil)
        #expect(찾기("きた", "くる") != nil)
        #expect(찾기("はなした", "はなす") != nil)
        #expect(찾기("はなして", "はなす") != nil)
    }

    @Test("줄지 않은 ている 도 되돌린다")
    func 진행형원형() {
        // 축약형 てる 만 있고 원형 ている 가 없었다. 그래서 문장에서 いる 가 통째로
        // 떨어져 나갔다 — 틀린 분절의 꼬리 1위가 `이루` 31건이었다.
        #expect(찾기("たべている", "たべる")?.rule == "진행형")
        #expect(찾기("よんでいる", "よむ")?.rule == "진행형")
        #expect(찾기("かいている", "かく")?.rule == "진행형")
        #expect(찾기("はなしている", "はなす")?.rule == "진행형")
        #expect(찾기("まっている", "まつ")?.rule == "진행형")
        #expect(찾기("きている", "くる") != nil)
        #expect(찾기("している", "する") != nil)
    }

    @Test("ていた 도 마찬가지다")
    func 진행형과거원형() {
        #expect(찾기("たべていた", "たべる")?.rule == "진행형 과거")
        #expect(찾기("よんでいた", "よむ")?.rule == "진행형 과거")
        #expect(찾기("かいていた", "かく")?.rule == "진행형 과거")
    }

    @Test("정중형 과거 ました")
    func 정중형과거() {
        // 1단은 어미만 갈면 되고, 5단은 어간이 い단으로 바뀌어 있다.
        #expect(찾기("たべました", "たべる") != nil)
        #expect(찾기("よみました", "よむ") != nil)
        #expect(찾기("かきました", "かく") != nil)
        #expect(찾기("きました", "くる") != nil)
    }

    @Test("5단 동사 정중형은 어간이 い단이다")
    func 오단정중형() {
        // ます 규칙이 "る"만 붙여서 よみます → よみる 가 됐다. 5단은 う단으로 돌려야 한다.
        #expect(찾기("よみます", "よむ") != nil)
        #expect(찾기("かきます", "かく") != nil)
        #expect(찾기("はなします", "はなす") != nil)
        // 1단도 그대로 되어야 한다.
        #expect(찾기("たべます", "たべる") != nil)
    }

    @Test("未然形 계열은 5단에서 어간이 あ단이다")
    func 미연형() {
        // 부정·수동·사역은 어미가 다를 뿐 어간을 되돌리는 방법이 같다.
        // 1단은 어미만 갈면 되고(たべない → たべる), 5단은 あ단을 う단으로 돌려야 한다.
        #expect(찾기("たべない", "たべる") != nil)
        #expect(찾기("よまない", "よむ") != nil)
        #expect(찾기("かかない", "かく") != nil)
        #expect(찾기("はなさない", "はなす") != nil)
        // う동사의 未然形은 わ 다 — かう → かわない.
        #expect(찾기("かわない", "かう") != nil)
    }

    @Test("수동·사역")
    func 수동사역() {
        #expect(찾기("たべられる", "たべる") != nil)
        #expect(찾기("たべられた", "たべる") != nil)
        #expect(찾기("よまれる", "よむ") != nil)
        #expect(찾기("よまれた", "よむ") != nil)
        #expect(찾기("たべさせる", "たべる") != nil)
        #expect(찾기("よませる", "よむ") != nil)
    }

    @Test("진행형 과거")
    func 진행형과거() {
        #expect(찾기("たべてた", "たべる")?.rule == "진행형 과거")
        #expect(찾기("よんでた", "よむ")?.rule == "진행형 과거")
    }

    // MARK: 빈도 목록에서 실제로 안 풀리던 것들
    //
    // 뜻이 빈 채로 남은 낱말 1,787개를 갈라 보니 세 갈래가 규칙 없이 새고 있었다 —
    // 맨 연용형 1,270개 · 부사형 44개 · 가능형 12개. 아래는 그 목록에서 그대로 가져온다.

    @Test("맨 연용형: い단 어간만 남은 꼴")
    func 연용형() {
        // 話し・分かり 처럼 ます 도 붙지 않은 어간이 코퍼스에 그대로 실려 있다.
        #expect(찾기("はなし", "はなす")?.rule == "연용형")
        #expect(찾기("わかり", "わかる")?.rule == "연용형")
        #expect(찾기("とりくみ", "とりくむ")?.rule == "연용형")
        #expect(찾기("おもい", "おもう")?.rule == "연용형")
        // 1단은 어간에 る 를 붙인다 — 食べ → 食べる
        #expect(찾기("たべ", "たべる")?.rule == "연용형")
    }

    @Test("い형용사 부사형: く → い")
    func 부사형() {
        #expect(찾기("おおきく", "おおきい")?.rule == "부사형")
        #expect(찾기("くわしく", "くわしい")?.rule == "부사형")
        #expect(찾기("うまく", "うまい")?.rule == "부사형")
        #expect(찾기("ただしく", "ただしい")?.rule == "부사형")
    }

    @Test("5단 가능형: え단 + る → う단")
    func 가능형() {
        #expect(찾기("つかえる", "つかう")?.rule == "가능형")
        #expect(찾기("はなせる", "はなす")?.rule == "가능형")
        #expect(찾기("およげる", "およぐ")?.rule == "가능형")
        // 이미 있던 불규칙과 어긋나지 않는다
        #expect(찾기("これる", "くる")?.rule == "가능형")
    }

    @Test("새 규칙이 이미 되던 것을 밀어내지 않는다")
    func 기존회귀() {
        // 부사형 규칙(く → い)이 5단 사전형 書く 를 건드리면 안 된다 — 원형은 그대로 남는다.
        #expect(Deinflector.candidates(for: "かく").first?.form == "かく")
        // 연용형 규칙이 명령형을 가리지 않는다
        #expect(찾기("がんばれ", "がんばる")?.rule == "명령형")
        // 가능형 규칙이 1단 사전형을 밀어내지 않는다
        #expect(Deinflector.candidates(for: "たべる").first?.form == "たべる")
    }
}
