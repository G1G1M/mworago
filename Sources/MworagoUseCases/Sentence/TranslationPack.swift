import Foundation

/// 문장을 옮겨 줄 번역 언어팩이 이 기기에 있는가.
///
/// **뜻 줄이 그냥 비어 있었다.** 일→한 언어팩을 안 받은 기기에서는 문장 뜻이 한 줄도
/// 안 뜨는데, 화면에는 아무 말이 없었다. 사용자가 보기에 그것은 "이 앱은 문장 뜻을
/// 안 준다"와 구별되지 않는다 — 받기만 하면 되는 일인데 받을 것이 있다는 사실을
/// 알 길이 없다. 심사하는 사람도 그 상태로 본다.
///
/// 낱말 뜻은 앱 안에 구워 들어 있어 언어팩과 상관없이 나온다. 안내가 그 사실을
/// 함께 말해야 앱 전체가 안 되는 것으로 읽히지 않는다.
public enum TranslationPack: Sendable, Equatable {
    /// 아직 물어보지 않았다. **이때는 아무 말도 하지 않는다** — 물어보기 전에 안내를
    /// 띄우면 언어팩이 멀쩡히 깔린 기기에서도 찾자마자 한 번 깜빡인다.
    case unknown
    /// 깔려 있다. 문장 뜻이 뜬다.
    case ready
    /// 기기는 할 수 있는데 언어팩을 아직 안 받았다. 사용자가 설정에서 받으면 된다.
    case needsDownload
    /// 이 기기·이 지역에서는 그 언어쌍을 옮길 수 없다. 사용자가 할 수 있는 일이 없다.
    case unsupported

    /// 문장 뜻이 뜨지 않는 자리에 대신 적을 말. 뜰 상태면 `nil`.
    ///
    /// **할 일이 있는 쪽과 없는 쪽을 가른다.** 한 문장으로 뭉뚱그리면 받을 수 없는
    /// 기기를 쓰는 사람을 설정 앱으로 헛걸음시킨다.
    public var notice: String? {
        switch self {
        case .unknown, .ready:
            nil
        case .needsDownload:
            "문장 뜻은 기기에 번역 언어팩이 있어야 뜹니다. "
                + "설정 앱 › 일반 › 언어 및 지역 › 번역 언어에서 일본어를 받으세요. "
                + "낱말 뜻은 그대로 나옵니다."
        case .unsupported:
            "이 기기에서는 문장 뜻을 옮겨 드릴 수 없습니다. 낱말 뜻은 그대로 나옵니다."
        }
    }
}
